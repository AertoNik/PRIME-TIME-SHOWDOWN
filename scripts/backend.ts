function readRun(): { pb: number; mailpit: number; dir: string; at: number } | null {
  try {
    return JSON.parse(fs.readFileSync(RUN_FILE, 'utf8'));
  } catch {
    return null;
  }
}

async function start(): Promise<void> {
  if (!binariesReady()) {
    log('PocketBase или Mailpit не установлены (или другой версии). Сначала выполните: npm run backend:install');
    proc.exit(1);
  }
  const apiUrl = `http://127.0.0.1:${DEV_PORTS.api}`;
  if (await healthy(apiUrl + '/api/health')) {
    log(`На ${apiUrl} уже кто-то отвечает — backend уже запущен? (npm run backend:status / npm run backend:stop)`);
    proc.exit(1);
  }
  const dir = path.resolve(arg('--dir') ?? DATA);
  fs.mkdirSync(dir, { recursive: true });
  fs.mkdirSync(RUN_DIR, { recursive: true });
  // 1.8.2: who may register is the SERVER's setting (the game only shows it): closed beta by default
  const registration = arg('--registration') ?? 'invite_only';
  if (!['invite_only', 'disabled', 'public'].includes(registration)) {
    log('--registration: invite_only | disabled | public');
    proc.exit(1);
  }
  const mail = spawnMailpit(DEV_PORTS);
  const pb = spawnPocketBase({ dir, ports: DEV_PORTS, origins: DEV_ORIGINS, env: { PRIME_REGISTRATION: registration, PRIME_GAME_URL: 'http://localhost:5173/' } });
  fs.writeFileSync(RUN_FILE, JSON.stringify({ pb: pb.pid, mailpit: mail.pid, dir, at: Date.now() }));
  const pipe = (child: { stdout: { on(e: string, f: (b: unknown) => void): void }; stderr: { on(e: string, f: (b: unknown) => void): void } }, tag: string) => {
    const out = (b: unknown) => {
      for (const line of String(b).split('\n')) {
        if (!line.trim()) continue;
        log(`[${tag}] ${line}`);
        if (line.includes('/_/#/pbinstall/')) log('\n>>> Первый запуск: откройте ссылку выше в браузере и создайте локального суперпользователя (свой email и пароль). <<<\n');
      }
    };
    child.stdout.on('data', out);
    child.stderr.on('data', out);
  };
  pipe(mail, 'MAIL');
  pipe(pb, 'PB');
  let stopping = false;
  const shutdown = async (code: number) => {
    if (stopping) return;
    stopping = true;
    log('Остановка backend…');
    await Promise.all([stopChild(pb), stopChild(mail)]);
    fs.rmSync(RUN_FILE, { force: true });
    log('Backend остановлен. Данные сохранены в ' + path.relative(proc.cwd(), dir));
    proc.exit(code);
  };
  proc.on('SIGINT', () => void shutdown(0));
  proc.on('SIGTERM', () => void shutdown(0));
  pb.on('exit', (c: number | null) => {
    if (!stopping) {
      log(`[PB] PocketBase завершился (код ${c}).`);
      void shutdown(c ?? 1);
    }
  });
  mail.on('exit', (c: number | null) => {
    if (!stopping) {
      log(`[MAIL] Mailpit завершился (код ${c}).`);
      void shutdown(c ?? 1);
    }
  });
  // a short summary once both answer
  for (let i = 0; i < 60; i++) {
    if ((await healthy(apiUrl + '/api/health')) && (await healthy(`http://127.0.0.1:${DEV_PORTS.mailUi}/livez`))) break;
    await sleep(250);
  }
  log('');
  log('PRIME NETWORK — локальный backend запущен (только на этом компьютере):');
  log(`  Регистрация:         ${registration === 'invite_only' ? 'CLOSED BETA — только по приглашению (npm run invites -- create 1)' : registration === 'public' ? 'PUBLIC — без приглашений (только для локальных опытов!)' : 'DISABLED — закрыта'}`);
  log(`  API PocketBase:      ${apiUrl}/api/`);
  log(`  Панель PocketBase:   ${apiUrl}/_/`);
  log(`  Тестовая почта:      http://127.0.0.1:${DEV_PORTS.mailUi}/`);
  const rel = path.relative(proc.cwd(), dir);
  log(`  Данные:              ${rel && !rel.startsWith('..') ? rel : dir}`);
  log('  Игра с аккаунтами:   npm run dev:accounts (в другой вкладке терминала),');
  log('                       затем откройте адрес Local из её вывода — http://localhost:5173/ (или 5174…5180)');
  log('  Остановить:          Ctrl+C');
  log('');
}

async function stop(): Promise<void> {
  const run = readRun();
  if (!run) {
    const up = await healthy(`http://127.0.0.1:${DEV_PORTS.api}/api/health`);
    log(up ? 'Backend отвечает, но запущен не через npm run backend — остановите его в том терминале (Ctrl+C).' : 'Backend не запущен.');
    return;
  }
  for (const pid of [run.pb, run.mailpit]) {
    if (pid && isAlive(pid)) {
      try {
        proc.kill(pid, 'SIGTERM');
      } catch {
        /* gone */
      }
    }
  }
  for (let i = 0; i < 40 && [run.pb, run.mailpit].some((p) => p && isAlive(p)); i++) await sleep(100);
  fs.rmSync(RUN_FILE, { force: true });
  log('Backend остановлен.');
}

async function status(): Promise<void> {
  const v = versions();
  log(`PocketBase: установлен ${installedVersion('pocketbase') ?? 'нет'} (нужен ${v.pocketbase.version})`);
  log(`Mailpit:    установлен ${installedVersion('mailpit') ?? 'нет'} (нужен ${v.mailpit.version})`);
  log(`API  ${DEV_PORTS.api}: ${(await healthy(`http://127.0.0.1:${DEV_PORTS.api}/api/health`)) ? 'работает' : 'не отвечает'}`);
  log(`Почта ${DEV_PORTS.mailUi}: ${(await healthy(`http://127.0.0.1:${DEV_PORTS.mailUi}/livez`)) ? 'работает' : 'не отвечает'}`);
}

/** Consistent copy (SQLite online backup — fine while the backend runs), checked, zipped. */
function backup(): void {
  const dir = path.resolve(arg('--dir') ?? DATA);
  if (!fs.existsSync(path.join(dir, 'data.db'))) {
    log(`В ${dir} нет базы (data.db) — копировать нечего.`);
    proc.exit(1);
  }
  const outRoot = path.resolve(arg('--out') ?? BACKUPS);
  const stamp = new Date().toISOString().replace(/[:T]/g, '-').slice(0, 19);
  const name = `pb_data-${stamp}`;
  const out = path.join(outRoot, name);
  const info = snapshot(dir, out);
  const zip = cp.spawnSync('/usr/bin/zip', ['-r', '-q', `${name}.zip`, name], { cwd: outRoot });
  if (zip.status !== 0) {
    log('Копия создана, но архив не собрался: ' + out);
    proc.exit(1);
  }
  const rel = (p: string) => (path.relative(proc.cwd(), p).startsWith('..') ? p : path.relative(proc.cwd(), p));
  log(`Копия базы (проверена PRAGMA integrity_check): ${rel(out)}`);
  log(`Архив: ${rel(out + '.zip')}`);
  log(`Внутри: аккаунтов ${info.counts.users}, сохранений ${info.counts.saves}, версий в истории ${info.counts.save_history}, приглашений ${Math.max(0, info.counts.invites)}`);
  log('Храните копию ещё и вне этого компьютера. Восстановление: docs/PRIME_CLOUD_BACKUP.md');
}

/** `npm run invites -- create 3 --days 14 --note "…"` → `pocketbase invites create 3 days=14 note=…` on the local data. */
function invites(): void {
  if (!fs.existsSync(PB_BIN)) {
    log('PocketBase не установлен: npm run backend:install');
    proc.exit(1);
  }
  const raw = proc.argv.slice(3);
  const args: string[] = [];
  let dir = DATA;
  for (let i = 0; i < raw.length; i++) {
    const a = raw[i];
    if (a === '--dir' && raw[i + 1]) dir = path.resolve(raw[++i]);
    else if (/^--(days|uses|note|count)$/.test(a) && raw[i + 1] !== undefined) args.push(`${a.slice(2)}=${raw[++i]}`);
    else args.push(a);
  }
  if (!fs.existsSync(path.join(dir, 'data.db'))) {
    log(`В ${dir} нет базы — сначала запустите npm run backend.`);
    proc.exit(1);
  }
  const r = cp.spawnSync(PB_BIN, ['invites', ...args, `--dir=${dir}`, `--hooksDir=${HOOKS}`, `--migrationsDir=${MIGRATIONS}`, '--automigrate=false'], {
    encoding: 'utf8',
    env: { ...proc.env, PRIME_SMTP_HOST: '127.0.0.1', PRIME_SMTP_PORT: String(DEV_PORTS.smtp), PRIME_APP_URL: `http://127.0.0.1:${DEV_PORTS.api}` },
  });
  // PocketBase prefixes every console line with a timestamp — not needed here
  const clean = (t: unknown) => String(t ?? '').replace(/^\d{4}\/\d\d\/\d\d \d\d:\d\d:\d\d ?/gm, '');
  proc.stdout.write(clean(r.stdout) + clean(r.stderr));
  proc.exit(r.status ?? 1);
}

/**
 * Prove that the current migrations leave a real database's accounts untouched — on a throwaway
 * copy in the system temp folder (deleted afterwards). The original backup is only read.
 */
async function migrateCheck(): Promise<void> {
  const src = proc.argv[3] ? path.resolve(proc.argv[3]) : '';
  if (!src || !fs.existsSync(src)) {
    log('Укажите резервную копию: npm run backend:migrate-check -- <папка с data.db, архив .zip или серверный .tar.gz>');
    proc.exit(1);
  }
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'prime-migrate-check-'));
  const dir = path.join(work, 'pb_data');
  fs.mkdirSync(dir);
  try {
    let from = src;
    if (src.endsWith('.age')) throw new Error('архив зашифрован (age): сначала расшифруйте его на Mac — docs/PRIME_CLOUD_BACKUP.md');
    if (src.endsWith('.zip') || src.endsWith('.tar.gz') || src.endsWith('.tgz')) {
      fs.mkdirSync(path.join(work, 'unzipped'));
      // 1.8.3: also the server's own archives (deploy/linux/backup.sh → pb_data-….tar.gz)
      if (src.endsWith('.zip')) cp.spawnSync('/usr/bin/unzip', ['-q', src, '-d', path.join(work, 'unzipped')]);
      else cp.spawnSync('/usr/bin/tar', ['-xzf', src, '-C', path.join(work, 'unzipped')]);
      const found = cp.spawnSync('/usr/bin/find', [path.join(work, 'unzipped'), '-name', 'data.db', '-not', '-path', '*/storage/*'], { encoding: 'utf8' }).stdout.split('\n').filter(Boolean)[0];
      if (!found) throw new Error('в архиве нет data.db');
      from = path.dirname(found);
    }
    for (const f of ['data.db', 'auxiliary.db']) if (fs.existsSync(path.join(from, f))) fs.copyFileSync(path.join(from, f), path.join(dir, f));
    const db = path.join(dir, 'data.db');
    const before = { counts: dbCounts(db), print: dbFingerprint(db) };
    log(`Копия: аккаунтов ${before.counts.users}, профилей ${before.counts.profiles}, сохранений ${before.counts.saves}, версий истории ${before.counts.save_history}`);
    const ports = { api: 18290, smtp: 11290, mailUi: 18291 };
    await ensurePortsFree([ports.api]);
    // a copy of the SERVER's database has its settings encrypted: the key comes only from this shell's
    // environment (typed with `read -rs PB_ENCRYPTION_KEY` — never an argument, never a file)
    const keyed = !!proc.env.PB_ENCRYPTION_KEY;
    const pb = spawnPocketBase({ dir, ports, origins: ['http://localhost:5173'], env: { PRIME_REGISTRATION: 'disabled' }, args: keyed ? ['--encryptionEnv=PB_ENCRYPTION_KEY'] : [] });
    const logs: string[] = [];
    pb.stdout.on('data', (b: unknown) => logs.push(String(b)));
    pb.stderr.on('data', (b: unknown) => logs.push(String(b)));
    const up = (await waitHealthy(`http://127.0.0.1:${ports.api}/api/health`)) && (await ownServerStarted(pb, logs));
    await stopChild(pb);
    if (!up && /message authentication failed|missing encryption key/.test(logs.join(''))) {
      throw new Error(keyed ? 'ключ PB_ENCRYPTION_KEY не подходит к этой копии (ничего не изменено)' : 'это копия с сервера: её настройки зашифрованы. Запустите проверку с ключом сервера — docs/PRIME_CLOUD_2_DEPLOY.md, шаг 2 (ничего не изменено)');
    }
    if (!up) throw new Error('PocketBase не запустился на копии:\n' + logs.join('').slice(-800));
    const after = { counts: dbCounts(db), print: dbFingerprint(db) };
    const mig = cp.spawnSync('/usr/bin/sqlite3', [db, "select file from _migrations where file like '%prime%' order by file;"], { encoding: 'utf8' }).stdout.trim().split('\n');
    const same = before.print === after.print && ['users', 'profiles', 'saves', 'save_history', 'invites'].every((t) => before.counts[t] === after.counts[t] || (t === 'invites' && before.counts[t] < 0));
    log(`Миграции PRIME на копии: ${mig.join(', ')}`);
    log(`Коллекция invites: ${after.counts.invites >= 0 ? 'есть' : 'НЕТ'} · game_sessions (1.8.3): ${after.counts.game_sessions >= 0 ? 'есть' : 'НЕТ'}`);
    log(same ? 'OK: аккаунты, хеши паролей, статусы email, никнеймы, сохранения, ревизии и история не изменились.' : 'ОШИБКА: данные на копии изменились — не применяйте эти миграции к рабочей базе!');
    if (!same || after.counts.invites < 0 || after.counts.game_sessions < 0) proc.exitCode = 1;
  } catch (e) {
    log('Проверка не прошла: ' + String((e as Error)?.message ?? e));
    proc.exitCode = 1;
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
    log('Временная копия удалена; исходная резервная копия не изменялась.');
  }
}

const cmd = proc.argv[2];
if (cmd === 'install') {
  try {
    install(log);
  } catch (e) {
    log('Ошибка установки: ' + String((e as Error)?.message ?? e));
    proc.exit(1);
  }
} else if (cmd === 'start') void start();
else if (cmd === 'stop') void stop();
else if (cmd === 'status') void status();
else if (cmd === 'backup') backup();
else if (cmd === 'rules') writeRules();
else if (cmd === 'invites') invites();
else if (cmd === 'migrate-check') void migrateCheck();
else if (cmd !== undefined) {
  log('Команды: install | start | stop | status | backup | rules | invites | migrate-check');
  proc.exit(1);
}
